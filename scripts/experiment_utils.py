ROOT = Path(__file__).resolve().parents[1]
BASE_CONFIG = ROOT / "config" / "base_experiment.yaml"
ACTIVE_CONFIG = ROOT / "config" / "active_experiment.yaml"
WORLD = ROOT / "worlds" / "sumo_research.wbt"


REQUIRED_IMPORTS = {
    "numpy": "numpy",
    "yaml": "PyYAML",
    "gymnasium": "gymnasium",
    "stable_baselines3": "stable-baselines3",
    "sb3_contrib": "sb3-contrib",
    "torch": "torch",
    "psutil": "psutil",
}


def check_python_environment() -> None:
    """Fail before opening Webots if the launcher Python lacks RL dependencies."""
    import importlib.util

    missing = [pip_name for module, pip_name in REQUIRED_IMPORTS.items()
               if importlib.util.find_spec(module) is None]
    if missing:
        req = ROOT / "requirements.txt"
        quoted_python = f'"{sys.executable}"'
        quoted_req = f'"{req}"'
        raise RuntimeError(
            "The Python environment running this benchmark is missing: "
            + ", ".join(missing)
            + "\n\nCurrent Python:\n  " + sys.executable
            + "\n\nInstall the project dependencies into THIS interpreter with:\n  "
            + quoted_python + " -m pip install -r " + quoted_req
            + "\n\nIf you created the supplied Conda environment, run the benchmark from "
              "'conda activate sumo_rl_research' first."
        )


def configure_webots_python() -> None:
    """Force Webots controllers to use the same interpreter as the launcher.

    Webots honors controller-local runtime.ini files. Generating them here keeps
    the project portable across Conda/venv installations and avoids relying on
    the global Webots Python preference.
    """
    python_exe = str(Path(sys.executable).resolve())
    contents = (
        "; Auto-generated by scripts/experiment_utils.py -- do not edit.\n"
        "; It binds this controller to the Python that launched the experiment.\n"
        "[python]\n"
        f"COMMAND = {python_exe}\n"
    )
    for controller_name in ("sumo_research", "arena_supervisor"):
        runtime = ROOT / "controllers" / controller_name / "runtime.ini"
        runtime.write_text(contents, encoding="utf-8")


def print_environment_banner() -> None:
    print(f"[python] {sys.executable}")
    print(f"[python] version={sys.version.split()[0]}")


def results_root(explicit: str | Path | None = None) -> Path:
    """Return a short, writable root for experiment outputs.

    Windows still encounters MAX_PATH problems in some Python/third-party paths,
    especially for TensorBoard and checkpoint filenames.  The project itself may
    live inside a long OneDrive path, so results default to a short directory in
    the user's home folder.  Override with --results-root or SUMO_RL_RESULTS_DIR.
    """
    if explicit:
        root = Path(explicit).expanduser()
    elif os.environ.get("SUMO_RL_RESULTS_DIR"):
        root = Path(os.environ["SUMO_RL_RESULTS_DIR"]).expanduser()
    elif os.name == "nt":
        root = Path.home() / "SumoRL_results"
    else:
        root = ROOT / "results"
    root = root.resolve()
    root.mkdir(parents=True, exist_ok=True)
    try:
        (ROOT / "RESULTS_LOCATION.txt").write_text(
            "Sumo RL experiment outputs are stored here:\n" + str(root) + "\n",
            encoding="utf-8",
        )
    except Exception:
        pass
    return root


def validate_run_path(cfg: Dict[str, Any]) -> None:
    """Fail early with a useful message if a Windows run path is still too long."""
    if os.name != "nt":
        return
    raw = cfg.get("experiment", {}).get("run_dir")
    if not raw:
        return
    p = Path(raw)
    if not p.is_absolute():
        p = ROOT / p
    # Reserve room for agent/checkpoint/tensorboard filenames used by SB3.
    probe = p / "agent_0" / "checkpoints" / "checkpoint_100000000_steps.zip"
    if len(str(probe)) >= 240:
        raise RuntimeError(
            "Experiment output path is too long for reliable Windows/Webots/SB3 file I/O.\n"
            f"Path length probe: {len(str(probe))} characters\n"
            f"Configured run_dir: {p}\n\n"
            "Use a shorter output root, for example:\n"
            r"  --results-root C:\SumoRL_results" + "\n"
            "or set SUMO_RL_RESULTS_DIR to a short directory."
        )


def load_yaml(path: Path) -> Dict[str, Any]:
    with path.open("r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def save_yaml(path: Path, data: Dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        yaml.safe_dump(data, f, sort_keys=False, allow_unicode=True)


def deep_merge(base: Dict[str, Any], override: Dict[str, Any]) -> Dict[str, Any]:
    out = copy.deepcopy(base)
    for key, value in override.items():
        if isinstance(value, dict) and isinstance(out.get(key), dict):
            out[key] = deep_merge(out[key], value)
        else:
            out[key] = copy.deepcopy(value)
    return out


def base_config() -> Dict[str, Any]:
    return load_yaml(BASE_CONFIG)


def locate_webots(explicit: str | None = None) -> str:
    if explicit:
        p = Path(explicit)
        if p.exists():
            return str(p)
        found = shutil.which(explicit)
        if found:
            return found
        raise FileNotFoundError(f"Webots executable not found: {explicit}")

    for name in ["webots", "webots.exe", "webots.bat"]:
        found = shutil.which(name)
        if found:
            return found

    home = os.environ.get("WEBOTS_HOME")
    candidates = []
    if home:
        candidates += [
            Path(home) / "msys64" / "mingw64" / "bin" / "webots.exe",
            Path(home) / "webots.exe",
            Path(home) / "webots",
        ]
    candidates += [
        Path(r"C:\Program Files\Webots\msys64\mingw64\bin\webots.exe"),
        Path(r"C:\Program Files\Webots\webots.exe"),
    ]
    for p in candidates:
        if p.exists():
            return str(p)
    raise FileNotFoundError(
        "Webots was not found. Pass --webots PATH or set WEBOTS_HOME."
    )


def _memory_snapshot(label: str = "memory") -> Dict[str, float]:
    """Return and print a compact process/system memory snapshot.

    psutil is deliberately a runner-only dependency.  It is not imported by the
    RL policy and does not change the scientific experiment.
    """
    import psutil

    proc = psutil.Process(os.getpid())
    vm = psutil.virtual_memory()
    snap = {
        "rss_mb": proc.memory_info().rss / (1024.0 ** 2),
        "system_available_mb": vm.available / (1024.0 ** 2),
        "system_percent": float(vm.percent),
    }
    print(
        f"[memory] {label}: runner_rss={snap['rss_mb']:.0f} MB "
        f"system_available={snap['system_available_mb']:.0f} MB "
        f"system_used={snap['system_percent']:.1f}%"
    )
    return snap


def memory_snapshot(label: str = "memory") -> Dict[str, float]:
    """Public wrapper used by benchmark orchestration scripts."""
    try:
        return _memory_snapshot(label)
    except Exception as exc:
        print(f"[memory] snapshot unavailable: {exc}")
        return {}


def _remember_descendants(root_pid: int, seen: Dict[int, float]) -> None:
    """Record descendants while the Webots launcher is alive.

    On Windows, Webots may create webots-bin plus Python controller processes.
    Capturing their PID + create_time lets us safely identify only processes that
    belong to this launch even if a PID is later reused.
    """
    import psutil

    try:
        root = psutil.Process(root_pid)
        children = root.children(recursive=True)
    except (psutil.NoSuchProcess, psutil.AccessDenied):
        return
    for child in children:
        try:
            seen.setdefault(child.pid, child.create_time())
        except (psutil.NoSuchProcess, psutil.AccessDenied):
            pass


def _cleanup_seen_processes(seen: Dict[int, float], grace_s: float = 4.0) -> None:
    """Wait for, then terminate only orphan descendants from one Webots launch."""
    import psutil

    candidates = []
    for pid, created in seen.items():
        try:
            p = psutil.Process(pid)
            # Protect against PID reuse.
            if abs(p.create_time() - created) < 0.25:
                candidates.append(p)
        except (psutil.NoSuchProcess, psutil.AccessDenied):
            pass

    if not candidates:
        return

    _gone, alive = psutil.wait_procs(candidates, timeout=grace_s)
    if alive:
        print(
            "[memory] cleaning lingering Webots/controller descendants: "
            + ", ".join(f"{p.name()}[{p.pid}]" for p in alive if p.is_running())
        )
        for p in alive:
            try:
                p.terminate()
            except (psutil.NoSuchProcess, psutil.AccessDenied):
                pass
        _gone, alive = psutil.wait_procs(alive, timeout=2.0)
        for p in alive:
            try:
                p.kill()
            except (psutil.NoSuchProcess, psutil.AccessDenied):
                pass
        if alive:
            psutil.wait_procs(alive, timeout=2.0)


def release_runner_memory() -> None:
    """Release Python-side temporary objects between independent Webots phases."""
    try:
        import matplotlib.pyplot as plt
        plt.close("all")
    except Exception:
        pass
    gc.collect()


def run_webots(cfg: Dict[str, Any], webots: str | None = None, visible: bool = False) -> None:
    """Run one isolated Webots phase and guarantee descendant cleanup.

    v1.13 is an orchestration-only reliability layer over the frozen v1.12
    experiment.  The scientific configuration is not altered.  The launcher is
    monitored so controller/webots-bin processes cannot silently accumulate over
    a multi-hour 20-policy benchmark.
    """
    check_python_environment()
    configure_webots_python()
    validate_run_path(cfg)
    save_yaml(ACTIVE_CONFIG, cfg)
    exe = locate_webots(webots)
    print_environment_banner()
    cmd = [exe, "--batch", "--mode=fast", "--stdout", "--stderr"]
    if not visible:
        cmd.append("--minimize")
    cmd.append(str(WORLD))
    print("\n[launcher]", " ".join(f'"{x}"' if " " in x else x for x in cmd))

    # Track only the process tree created by this launch.  This avoids broad
    # taskkill commands that could terminate the user's unrelated Python work.
    import psutil
    seen_descendants: Dict[int, float] = {}
    proc = subprocess.Popen(cmd, cwd=str(ROOT))
    poll_interval_s = max(0.5, float(os.environ.get("SUMO_RL_PROCESS_POLL_S", "1.0")))
    report_every_s = max(10.0, float(os.environ.get("SUMO_RL_MEMORY_REPORT_S", "60")))
    min_free_mb = max(0.0, float(os.environ.get("SUMO_RL_MIN_FREE_MB", "768")))
    last_report = 0.0
    low_memory_hits = 0

    try:
        while True:
            _remember_descendants(proc.pid, seen_descendants)
            rc = proc.poll()
            if rc is not None:
                break

            now = time.monotonic()
            vm = psutil.virtual_memory()
            free_mb = vm.available / (1024.0 ** 2)
            if now - last_report >= report_every_s:
                memory_snapshot("Webots phase running")
                last_report = now

            # Avoid a hard Windows out-of-memory crash.  Three consecutive low
            # readings are required to ignore transient cache pressure.  Because
            # the benchmark is resumable at phase boundaries, failing explicitly
            # is preferable to corrupting an hours-long run.
            if min_free_mb > 0 and free_mb < min_free_mb:
                low_memory_hits += 1
            else:
                low_memory_hits = 0
            if low_memory_hits >= 3:
                raise MemoryError(
                    f"Available system memory stayed below {min_free_mb:.0f} MB. "
                    "The phase was stopped before Windows exhausted memory. "
                    "Use the memory-safe resume command after freeing RAM."
                )
            time.sleep(poll_interval_s)
    except BaseException:
        try:
            if proc.poll() is None:
                proc.terminate()
                try:
                    proc.wait(timeout=3.0)
                except subprocess.TimeoutExpired:
                    proc.kill()
                    proc.wait(timeout=3.0)
        finally:
            _cleanup_seen_processes(seen_descendants)
            release_runner_memory()
        raise

    # Capture a final generation of children before cleanup if the root still
    # exists long enough to query it.
    _remember_descendants(proc.pid, seen_descendants)
    _cleanup_seen_processes(seen_descendants)
    release_runner_memory()
    memory_snapshot("after Webots cleanup")

    if rc != 0:
        raise RuntimeError(f"Webots exited with code {rc}")


def timestamp_id(prefix: str) -> str:
    return time.strftime("%Y%m%d_%H%M%S_") + prefix


def as_relative_or_absolute(path: Path) -> str:
    try:
        return str(path.resolve().relative_to(ROOT.resolve()))
    except Exception:
        return str(path.resolve())
